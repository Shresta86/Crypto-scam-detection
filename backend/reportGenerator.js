const DISCLAIMER_FOOTER = 'Prototype report generated by TraceX for demonstration purposes';

function shortAddr(addr) {
  if (!addr || addr.length < 12) return addr || '';
  return `${addr.slice(0, 6)}...${addr.slice(-4)}`;
}

function shortHash(hash) {
  if (!hash || hash.length < 14) return hash || '';
  return `${hash.slice(0, 8)}...${hash.slice(-6)}`;
}

function drawEmblem(pdf, x, y, size = 32) {
  pdf.save();
  pdf.strokeColor('#10263f').lineWidth(1.5);
  // Outer shield
  pdf.moveTo(x, y)
    .lineTo(x + size, y)
    .lineTo(x + size, y + size * 0.6)
    .quadraticCurveTo(x + size * 0.5, y + size * 1.1, x + size * 0.5, y + size * 1.1)
    .quadraticCurveTo(x, y + size * 0.6, x, y + size * 0.6)
    .closePath()
    .stroke();
  
  // Inner crest scale/cross
  pdf.lineWidth(1).strokeColor('#2563EB');
  pdf.moveTo(x + size * 0.25, y + size * 0.4).lineTo(x + size * 0.75, y + size * 0.4).stroke();
  pdf.moveTo(x + size * 0.5, y + size * 0.2).lineTo(x + size * 0.5, y + size * 0.8).stroke();
  pdf.restore();
}

function drawTable(pdf, startX, startY, colWidths, headers, rows) {
  const tableWidth = colWidths.reduce((a, b) => a + b, 0);
  let curY = startY;

  // Header row
  pdf.save().rect(startX, curY, tableWidth, 18).fill('#1E293B').restore();
  let curX = startX;
  pdf.font('Helvetica-Bold').fontSize(7.5).fillColor('#FFFFFF');
  headers.forEach((h, i) => {
    pdf.text(h, curX + 4, curY + 5, { width: colWidths[i] - 8, lineBreak: false });
    curX += colWidths[i];
  });
  curY += 18;

  // Data rows
  rows.forEach((row, rIdx) => {
    if (curY > pdf.page.height - 70) {
      pdf.addPage();
      curY = 56;
      // Re-print header
      pdf.save().rect(startX, curY, tableWidth, 18).fill('#1E293B').restore();
      let hX = startX;
      pdf.font('Helvetica-Bold').fontSize(7.5).fillColor('#FFFFFF');
      headers.forEach((h, i) => {
        pdf.text(h, hX + 4, curY + 5, { width: colWidths[i] - 8, lineBreak: false });
        hX += colWidths[i];
      });
      curY += 18;
    }

    const rowBg = rIdx % 2 === 0 ? '#F8FAFC' : '#FFFFFF';
    pdf.save().rect(startX, curY, tableWidth, 16).fill(rowBg).restore();
    pdf.save().rect(startX, curY, tableWidth, 16).strokeColor('#E2E8F0').lineWidth(0.5).stroke().restore();

    let cellX = startX;
    pdf.font('Times-Roman').fontSize(7.5).fillColor('#0F172A');
    row.forEach((cell, cIdx) => {
      pdf.text(String(cell ?? ''), cellX + 4, curY + 4, { width: colWidths[cIdx] - 8, lineBreak: false });
      cellX += colWidths[cIdx];
    });
    curY += 16;
  });

  return curY + 10;
}

